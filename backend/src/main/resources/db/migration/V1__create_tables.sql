-- 一度流した SQL は、あとから書き換えない（変えたいときは、V2__…sql を足す）。

-- 列（ToDo / 作業中 / 完了）
CREATE TABLE board_column (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(255) NOT NULL,
    sort_order integer      NOT NULL
);

-- カード
CREATE TABLE card (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       varchar(255)  NOT NULL,
    description varchar(2000),
    color       varchar(255)  NOT NULL,
    due_date    date,
    column_id   bigint        NOT NULL,
    position    integer       NOT NULL,
    CONSTRAINT fk_card_column FOREIGN KEY (column_id) REFERENCES board_column (id)
);

-- 背景の設定（1件だけ。id はいつも 1）
CREATE TABLE board_setting (
    id         bigint PRIMARY KEY,
    background varchar(255) NOT NULL
);

-- 自分の背景画像（割り当て先ごとに、最大1枚）
CREATE TABLE user_background_image (
    slot       varchar(255) PRIMARY KEY,
    image      bytea                    NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL
);
